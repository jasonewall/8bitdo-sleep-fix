#!/bin/sh

VENDOR_ID=2dc8

echo "===================================================="
echo "⚡ 8BitDo Sleep Fix: Auto-ID & Port Discovery ⚡"
echo "===================================================="
echo ""

# --- STEP 1: CAPTURE ACTIVE STATE ---
echo "👉 STEP 1: Turn ON every 8BitDo controller you want to fix."
echo "Make sure they are fully connected to your system right now."
read -p "Press [ENTER] once all controllers are ON and connected..."
echo ""

TMPDIR=$(mktemp -d)
trap 'rm -rf "$TMPDIR"' EXIT

# Collect every 8BitDo device that is currently in its ACTIVE state.
# (Skip anything whose product name contains "IDLE".)
: > "$TMPDIR/active"
for f in /sys/bus/usb/devices/*/idVendor; do
    [ -f "$f" ] || continue
    [ "$(cat "$f" 2>/dev/null)" = "$VENDOR_ID" ] || continue
    d=$(dirname "$f")
    port=$(basename "$d")
    case "$port" in *:*) continue;; esac
    [ -f "$d/idProduct" ] || continue
    name=$(cat "$d/product" 2>/dev/null || echo "")
    case "$name" in *IDLE*|*idle*) continue;; esac
    pid=$(cat "$d/idProduct")
    echo "$port $pid $name" >> "$TMPDIR/active"
done

if [ ! -s "$TMPDIR/active" ]; then
    echo "❌ Error: Could not find any active 8BitDo device. Check your connection."
    exit 1
fi

echo "✅ Found active controllers:"
while IFS= read -r line; do
    set -- $line
    port=$1
    pid=$2
    shift 2
    name=$*
    echo "   port=$port  product_id=$pid  name='$name'"
done < "$TMPDIR/active"
echo ""

# --- STEP 2: CAPTURE INACTIVE STATE ---
echo "👉 STEP 2: Now turn OFF (or dock) all of those controllers."
read -p "Press [ENTER] once all controllers are completely OFF..."
echo ""

# Wait for every device to settle (disappear or change product id).
i=0
while [ $i -lt 40 ]; do
    all_settled=1
    while IFS= read -r line; do
        set -- $line
        port=$1
        active_pid=$2
        if [ -d "/sys/bus/usb/devices/$port" ]; then
            cur=$(cat "/sys/bus/usb/devices/$port/idProduct" 2>/dev/null || echo "")
            if [ "$cur" = "$active_pid" ]; then
                all_settled=0
            fi
        fi
    done < "$TMPDIR/active"
    [ "$all_settled" -eq 1 ] && break
    sleep 0.5
    i=$((i + 1))
done

: > "$TMPDIR/idle"
fail=0
while IFS= read -r line; do
    set -- $line
    port=$1
    active_pid=$2
    shift 2
    name=$*

    if [ ! -d "/sys/bus/usb/devices/$port" ]; then
        idle=none
    else
        idle=$(cat "/sys/bus/usb/devices/$port/idProduct" 2>/dev/null || echo "")
        if [ -z "$idle" ]; then
            idle=none
        fi
        if [ "$idle" = "$active_pid" ]; then
            echo "⚠️  Warning: $port still reports the active ID ($active_pid)."
            fail=1
        fi
    fi

    echo "$port $active_pid $idle" >> "$TMPDIR/idle"
    echo "   port=$port  active=$active_pid  inactive=$idle  name='$name'"
done < "$TMPDIR/active"
echo ""

if [ "$fail" -ne 0 ]; then
    echo "❌ Some controllers did not power off. Make sure they are fully off and try again."
    exit 1
fi

# --- GENERATE CONFIG ---
count=0
{
    echo "# Generated by detect.sh"
    echo "VENDOR_ID=$VENDOR_ID"
    while IFS= read -r line; do
        set -- $line
        port=$1
        active_pid=$2
        idle=$3
        count=$((count + 1))
        hub="usb$(echo "$port" | cut -d'-' -f1)"
        echo "DEVICE_${count}_PORT=$port"
        echo "DEVICE_${count}_HUB=$hub"
        echo "DEVICE_${count}_PRODUCT_ID=$active_pid"
        echo "DEVICE_${count}_IDLE_PRODUCT_ID=$idle"
    done < "$TMPDIR/idle"
    echo "DEVICE_COUNT=$count"
} > 8bitdo-sleep-fix.env

echo "✅ Wrote 8bitdo-sleep-fix.env ($count device(s))."
echo ""